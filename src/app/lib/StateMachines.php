<?php
/**
 * The registry of explicit state machines, and their exports.
 *
 * Add a machine here and it appears in docs/STATE_MACHINES.md and in
 * assets/js/state-machines.js the next time tools/gen_state_machines.php runs;
 * verify.sh runs it with --check so neither can drift from the code.
 */

declare(strict_types=1);

final class StateMachines
{
    /** @return array<string, StateMachine> */
    public static function all(): array
    {
        $out = [];
        foreach ([
            CompanionRoster::machine(),
            LifeState::machine(),
            QuestStatus::machine(),
            CombatStatus::machine(),
            UiMode::machine(),
            TrapState::machine(),
        ] as $m) {
            $out[$m->name] = $m;
        }
        return $out;
    }

    public static function get(string $name): StateMachine
    {
        $all = self::all();
        if (!isset($all[$name])) {
            throw new InvalidArgumentException("No state machine called {$name}");
        }
        return $all[$name];
    }

    /** Everything, as plain data. */
    public static function export(): array
    {
        return array_map(static fn (StateMachine $m) => $m->toArray(), self::all());
    }

    /** The JS mirror: window.RivermarkStates, plus named constants per machine. */
    public static function javascript(): string
    {
        $data = json_encode(self::export(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        return <<<JS
/*
 * GENERATED by src/tools/gen_state_machines.php from src/app/lib/StateMachines.php.
 * Do not edit by hand: verify.sh fails when this file is stale.
 *
 * window.RivermarkStates.machines   every machine as data (states, transitions, terminal)
 * window.RivermarkStates.S.<machine>.<STATE>   the state names as constants
 * window.RivermarkStates.can(machine, from, to)   is that move in the table?
 */
(function () {
  'use strict';
  const machines = {$data};
  const S = {};
  Object.keys(machines).forEach((name) => {
    S[name] = {};
    Object.keys(machines[name].states).forEach((st) => { S[name][st.toUpperCase()] = st; });
  });
  function can(name, from, to) {
    const m = machines[name];
    return !!m && m.transitions.some((t) => t.from === from && t.to === to);
  }
  function isTerminal(name, st) {
    const m = machines[name];
    return !!m && m.terminal.includes(st);
  }
  window.RivermarkStates = Object.freeze({ machines, S, can, isTerminal });
})();

JS;
    }

    /** docs/STATE_MACHINES.md. */
    public static function markdown(): string
    {
        $md = "# State machines\n\n"
            . "<!-- GENERATED by src/tools/gen_state_machines.php — edit src/app/lib/*.php machine() tables, then run\n"
            . "     `php src/tools/gen_state_machines.php`. verify.sh fails when this file is stale. -->\n\n"
            . "Every lifecycle the game enforces is declared once, as a table, in `src/app/lib/`. The server\n"
            . "guards each status write with `StateMachine::guard()` / `allows()` (illegal moves are refused\n"
            . "and logged as `[state-machine] illegal transition {...}` in the PHP error log); the client reads\n"
            . "the same tables from `assets/js/state-machines.js` (`window.RivermarkStates`). Machine-readable\n"
            . "copy for agents: the JSON block under each heading, or `php src/tools/gen_state_machines.php --json`.\n\n"
            . "Implicit machines that were audited but deliberately left as they are are listed in\n"
            . "`docs/STATE_MACHINES_AUDIT.md`.\n\n";
        foreach (self::all() as $m) {
            $md .= "## {$m->title} (`{$m->name}`)\n\n";
            $md .= "Stored in: {$m->storage}\n\n";
            $md .= "```mermaid\n" . $m->mermaid() . "\n```\n\n";
            $md .= "| State | Meaning |\n|---|---|\n";
            foreach ($m->states as $s => $meaning) {
                $tag = $s === $m->initial ? ' (initial)' : ($m->isTerminal($s) ? ' (terminal)' : '');
                $md .= "| `{$s}`{$tag} | " . str_replace('|', '\\|', $meaning) . " |\n";
            }
            $md .= "\n| From | Event | To |\n|---|---|---|\n";
            foreach ($m->edges() as $e) {
                $md .= "| `{$e['from']}` | {$e['event']} | `{$e['to']}` |\n";
            }
            if ($m->notes !== '') {
                $md .= "\n{$m->notes}\n";
            }
            $md .= "\n<details><summary>JSON</summary>\n\n```json\n"
                . json_encode($m->toArray(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)
                . "\n```\n\n</details>\n\n";
        }
        return $md;
    }
}
