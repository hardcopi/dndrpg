    /**
     * How a level is shaped, by how deep it is.
     *
     * `fights` is the share of the level's rooms that hold something to kill,
     * expressed as a tier name the encounter budget understands. Deeper levels
     * are not merely harder fights: they are bigger, more tangled, and more of
     * what is in them is alive.
     *
     * Room counts came DOWN when passages became places you stand in. A floor
     * is walked in locations, not in rooms: eleven rooms joined by twelve
     * passages is a twenty-three stop journey, and the old counts turned a
     * level into a route march. What a player should feel is that the rooms
     * have distance between them, not that there are more of them.
     */
    /**
