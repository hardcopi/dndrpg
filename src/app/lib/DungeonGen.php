     * that keeps floor six from feeling like floor three.
     *
     * Deadly is still not reachable, deliberately — see EncounterBudget, which
     * refuses to name a tier whose honest description is "you will probably
     * die". Depth scaling can push a hard fight past it; a table cannot.
     */
