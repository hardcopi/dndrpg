    /**
     * One level, complete, from a seed.
     *
     * Deterministic: the same seed and depth build the same dungeon, every
     * time, on every machine. That is what lets a delve be stored as a seed and
     * a depth rather than as a hundred rows, and what lets a bug be reported as
     * a number.
     *
     * @return array{
     *   seed:int, depth:int, profile:string,
     *   rooms: array<int, array{id:int, gx:int, gy:int, w:int, h:int,
     *                           x:float, y:float, kind:string, role:string,
     *                           name:string, description:string}>,
     *   edges: array<int, array{a:int, b:int, door:string}>,
     *   corridors: list<array{id:int, a:int, b:int, door:string,
     *                         name:string, description:string}>,
     *   entrance:int, stair:int
     * }
     */
    public static function generate(int $seed, int $depth): array
    {
        $profile = self::profileForDepth($depth);
        $spec = self::PROFILES[$profile];
        $rng = ($seed ^ ($depth * 0x9E3779B1)) & 0xFFFFFFFF;

        $rooms = self::placeRooms($rng, $spec['rooms'][0], $spec['rooms'][1]);
        $edges = self::joinRooms($rng, $rooms, self::rint($rng, $spec['loops'][0], $spec['loops'][1]));

        return self::finish($rng, $seed, $depth, $profile, $rooms, $edges);
    }

    /**
     * Everything a layout needs to become a level.
     *
     * Split out of generate() so that a layout from somewhere else can have it
     * too. GeneratedLevel builds its rooms and edges from the map service and
     * then calls this, which is why a floor from the service is stocked, named,
     * dressed and trapped by the same code as one from here — the parts of a
     * dungeon that are about the GAME rather than about the shape of the place.
     *
     * A caller with its own prose passes it in `$names`, keyed by room id, and
     * whatever it does not name is named here. That is the whole of the seam:
     * the service knows what a room is called, this knows what is standing in
     * it, and neither has an opinion about the other.
     *
     * @param  array<int,array{name:string,description:string}> $names
     */
    public static function finish(
        int &$rng,
        int $seed,
        int $depth,
        string $profile,
        array $rooms,
        array $edges,
        array $names = []
    ): array {
        $spec = self::PROFILES[$profile];

        // Entrance and stair as far apart as the plan allows, so a level is a
        // journey rather than a doorway. Chosen before stocking, because both
        // are roles that override whatever the contents table would have said.
        [$entrance, $stair] = self::endpoints($rooms, $edges);
        self::unsealEntrance($edges, $entrance);
        self::stock($rng, $rooms, $entrance, $stair, $spec['boss']);
        self::describe($rng, $rooms, $profile);

        // Borrowed prose wins, room by room. Applied after describe() rather
        // than instead of it so that a caller that names half its rooms still
        // gets a name for the other half.
        foreach ($rooms as $i => $room) {
            $given = $names[(int) $room['id']] ?? null;
            if ($given === null) {
                continue;
            }
            if (!empty($given['name'])) {
                $rooms[$i]['name'] = (string) $given['name'];
            }
            if (!empty($given['description'])) {
                $rooms[$i]['description'] = (string) $given['description'];
            }
        }

        // One passage per edge, given its own identity. An edge used to be a
        // line between two rooms and nothing else; it is now somewhere the
        // party stands, so it needs a name and a description like anything
        // else that has a scene. Its SHAPE still belongs to plan(), which is
        // the only place the two grids meet.
        $corridors = self::passages($rng, $edges, $profile);

        // The dressing: locked and rigged doors, passage traps, and the
        // level's one atmosphere. On its OWN stream — see dress().
        $atmosphere = self::dress($seed, $depth, $profile, $rooms, $edges, $corridors, $entrance);

        return [
            'seed'       => $seed,
            'depth'      => $depth,
            'profile'    => $profile,
            'rooms'      => $rooms,
            'edges'      => $edges,
            'corridors'  => $corridors,
            'entrance'   => $entrance,
            'stair'      => $stair,
            'atmosphere' => $atmosphere,
        ];
    }

    /**
     * Refine a generated level: door subtypes, traps, atmosphere.
     *
     * ON ITS OWN RNG STREAM, and that is the load-bearing fact about it. Every
     * open delve is stored as a seed and rebuilt from it whenever anything
     * looks — planFor() for the chart, status() for the stair — so the main
     * stream's call sequence is effectively a save format. This pass draws from
     * a second splitmix32 state derived from the same seed with different
     * mixing, consumed only here, after the whole of the old pipeline has run:
     * the layout, stocking, names and prose for every (seed, depth) that
     * existed before dressing did are byte-identical after it. The golden-hash
     * test in tools/test_dungeon.php holds that promise; if a new feature needs
     * randomness, it takes it from THIS stream, below the last existing draw.
     *
     * Rolls are consumed unconditionally — one per edge, one per corridor —
     * whether or not the result is used, so a future change to which doors are
     * upgradable cannot shift any roll after it.
     *
     * @return array{key:string,label:string,air:string,light:string} the pick
     */
    private static function dress(
        int $seed,
        int $depth,
        string $profile,
        array &$rooms,
        array &$edges,
        array &$corridors,
        int $entrance
    ): array {
        $rng = (self::mul32($seed, 0x85EBCA6B) ^ self::mul32($depth, 0xC2B2AE35) ^ 0x00D4E551) & 0xFFFFFFFF;

        // --- doors -----------------------------------------------------------
        // Only the plain 'door' upgrades. open and arch stay honest gaps;
        // stuck keeps its one privilege of being hidden.
        foreach ($edges as $i => $e) {
            $roll = self::rint($rng, 1, 100);
            if ($e['door'] !== 'door') {
                continue;
            }
            if ($roll <= self::DOOR_LOCKED_PCT) {
                $edges[$i]['door'] = 'locked';
            } elseif ($roll <= self::DOOR_LOCKED_PCT + self::DOOR_PORTCULLIS_PCT) {
                $edges[$i]['door'] = 'portcullis';
            } elseif ($roll <= self::DOOR_LOCKED_PCT + self::DOOR_PORTCULLIS_PCT + self::DOOR_TRAPPED_PCT) {
                $edges[$i]['door'] = 'trapped';
            }
        }

        // --- traps -----------------------------------------------------------
        // A trapped door's trap and a passage's own trap are one mechanism: the
        // spec sits on the corridor, because the passage is where the party is
        // standing when it goes off. The cap counts both kinds, so a level can
        // never be more toll-booth than dungeon; door-traps claim their share
        // first (a rigged door past the cap quietly reverts to plain), then the
        // passages roll for what remains.
        $band = $profile;
        $trapped = 0;
        foreach ($edges as $i => $e) {
            if ($e['door'] !== 'trapped') {
                continue;
            }
            if ($trapped >= self::TRAP_CAP) {
                $edges[$i]['door'] = 'door';
                continue;
            }
            $corridors[$i]['trap'] = self::DOOR_TRAPS[$band];
            $trapped++;
        }
        foreach ($corridors as $i => $c) {
            $roll = self::rint($rng, 1, 100);
            $pick = self::rint($rng, 0, count(self::TRAPS[$band]) - 1);
            if (isset($c['trap']) || $roll > self::PASSAGE_TRAP_PCT || $trapped >= self::TRAP_CAP) {
                continue;
            }
            $corridors[$i]['trap'] = self::TRAPS[$band][$pick];
            $trapped++;
        }

        // --- the entrance re-guard -------------------------------------------
        // unsealEntrance() promised a way out of the arrival room that needs no
        // searching; the dressing must not take it back. Locked and portcullis
        // shut it, and a trap on the only free way makes the mandatory first
        // step of every delve a toll rather than a step — so at least one edge
        // out of the entrance must be walkable AND unrigged. Runs after all the
        // dressing so nothing can re-seal behind it; rng-free, like the
        // original, and for the same reason.
        $free = false;
        $walkableRigged = null;
        $shut = null;
        foreach ($edges as $i => $e) {
            if ($e['a'] !== $entrance && $e['b'] !== $entrance) {
                continue;
            }
            if (in_array($e['door'], ['open', 'arch', 'door'], true)) {
                if (!isset($corridors[$i]['trap'])) {
                    $free = true;
                } elseif ($walkableRigged === null) {
                    $walkableRigged = $i;
                }
            } elseif ($e['door'] !== 'stuck' && $shut === null) {
                $shut = $i; // locked, portcullis or trapped
            }
        }
        if (!$free) {
            if ($walkableRigged !== null) {
                unset($corridors[$walkableRigged]['trap']);
            } elseif ($shut !== null) {
                $edges[$shut]['door'] = 'door';
                unset($corridors[$shut]['trap']);
            }
        }

        // Doors live on the edge and are described twice; keep the copies one.
        foreach ($corridors as $i => $c) {
            $corridors[$i]['door'] = $edges[$i]['door'];
        }

        // --- atmosphere ------------------------------------------------------
        // One pick per floor, threaded thin: the entrance room and a third of
        // the passages carry a clause of it, alternating what the air does and
        // what the light finds, so the level says the same thing in more than
        // one voice without saying it everywhere.
        $atmo = self::ATMOSPHERE[$band][self::rint($rng, 0, count(self::ATMOSPHERE[$band]) - 1)];
        $rooms[$entrance]['description'] .= ' ' . $atmo['air'];
        foreach ($corridors as $i => $c) {
            $roll = self::rint($rng, 1, 3);
            if ($roll === 1) {
                $corridors[$i]['description'] .= ' ' . $atmo[$i % 2 === 0 ? 'air' : 'light'];
            }
        }

        // --- furnishings -----------------------------------------------------
        // LAST, and on this stream rather than the main one, which is the rule
        // this whole function exists to keep: "if a new feature needs
        // randomness, it takes it from THIS stream, below the last existing
        // draw". Putting these three rolls in stock() instead moved the golden
        // hash on the first run — every layout for every (seed, depth) that
        // already existed would have come back different, which is the save-rot
        // the hash is there to catch. Below the atmosphere block for the same
        // reason: anything added above it shifts every roll after it.
        self::furnish($rng, $rooms, $depth, $band);

        return $atmo;
    }

    /**
     * One passage per edge: an id, the rooms it joins, and its own scene.
     *
     * Indexed by the edge it came from, so `corridors[$i]` and `edges[$i]` are
     * the same connection described twice — the layout's view of it and the
     * player's. Nothing has to be matched up later.
     *
     * @param  array $edges as built by joinRooms()
     * @return list<array{id:int, a:int, b:int, door:string, name:string, description:string}>
     */
    private static function passages(int &$rng, array $edges, string $profile): array
    {
        $band = self::PASSAGE_PROSE[$profile];
        $names = self::deal($rng, self::PASSAGE_NAMES[$profile]);
        $decks = [
            'run'    => self::deal($rng, $band['run']),
            'detail' => self::deal($rng, $band['detail']),
        ];
        $last = ['run' => '', 'detail' => ''];

        $out = [];
        foreach ($edges as $i => $edge) {
            $run = self::draw($rng, $decks['run'], $band['run'], $last['run']);
            $detail = self::draw($rng, $decks['detail'], $band['detail'], $last['detail']);
            $out[] = [
                'id'          => $i,
                'a'           => (int) $edge['a'],
                'b'           => (int) $edge['b'],
                'door'        => (string) $edge['door'],
                'name'        => self::nameDeck($names, $i),
                'description' => "{$run}. {$detail}",
            ];
        }
        return $out;
    }

    // =======================================================================
    // Layout
    // =======================================================================

    /**
     * Rooms, on the coarse plan, not overlapping and not touching.
     *
     * Bounded retries and a silent give-up, which is BattleMapGen's rule and is
     * right for the same reason: a level with nine rooms instead of ten is not
     * worth stalling a request over. The floor of MIN_ROOMS is the only hard
     * requirement, and `generate()` cannot be asked for fewer.
     *
     * Rooms are kept one plan-cell apart so that a corridor always has
     * somewhere to run, and so that two rooms never share a wall and read as
     * one shape on the drawn plan.
     */
    private static function placeRooms(int &$rng, int $min, int $max): array
    {
        $want = self::rint($rng, $min, $max);
        $rooms = [];

        for ($attempt = 0; $attempt < $want * 12 && count($rooms) < $want; $attempt++) {
            $w = self::rint($rng, 1, 2);
            $h = self::rint($rng, 1, 2);
            $gx = self::rint($rng, 0, self::GRID_W - $w);
            $gy = self::rint($rng, 0, self::GRID_H - $h);

            if (!self::fits($rooms, $gx, $gy, $w, $h)) {
                continue;
            }
            $rooms[] = [
                'id' => count($rooms), 'gx' => $gx, 'gy' => $gy, 'w' => $w, 'h' => $h,
                'x' => 0.0, 'y' => 0.0, 'kind' => 'empty', 'role' => 'room',
                'name' => '', 'description' => '',
            ];
        }

        // Project onto the chart's field. The centre of the room's plan
        // footprint becomes the node's position; project() is the only place
        // the conversion is written, and plan() reaches for the same one.
        foreach ($rooms as $i => $r) {
            [$x, $y] = self::project($r['gx'] + $r['w'] / 2, $r['gy'] + $r['h'] / 2);
            $rooms[$i]['x'] = $x;
            $rooms[$i]['y'] = $y;
        }
        return $rooms;
    }

    /**
     * Plan cell to chart field. The one conversion between the two grids.
     *
     * The header promises the projection happens once and nothing downstream
     * converts anything again. It was written inline in placeRooms() and that
     * promise held only because nothing else needed it — the moment plan()
     * wanted room CORNERS as well as centres there would have been two copies
     * of the same arithmetic, and a margin changed in one of them is a floor
     * plan that no longer sits under its own labels.
     *
     * The 8 and 7 are margins: a name is written under a node, and a node on
     * the bottom row needs its caption to stay inside what ui-map.js pads for.
     *
     * @return array{0:float, 1:float}
     */
    public static function project(float $gx, float $gy, ?int $gw = null, ?int $gh = null): array
    {
        $gw ??= self::GRID_W;
        $gh ??= self::GRID_H;
        return [
            round(8 + ($gx / $gw) * (self::VIEW_W - 16), 2),
            round(7 + ($gy / $gh) * (self::VIEW_H - 16), 2),
        ];
    }

    /**
     * The lattice a level is drawn on: width, height, and tiles per cell.
     *
     * Authored levels and this generator's own say nothing and get the
     * constants, which is every level that existed before the map service. A
     * level from the service carries its own — its rooms are rectangles on a
     * 64x48 tile grid rather than slots on a 9x7 one — and everything
     * downstream reads the numbers rather than assuming them.
     *
     * Which is the whole trick: the chart, the fog raster and the passage
     * router are resolution-independent already; they were simply never told
     * they could be anything else. `sub` is 1 for a level whose rooms are
     * already measured in tiles.
     *
     * @return array{0:int,1:int,2:int} grid width, grid height, sub-tiles per cell
     */
    public static function gridOf(array $level): array
    {
        return [
            (int) ($level['grid_w'] ?? self::GRID_W),
            (int) ($level['grid_h'] ?? self::GRID_H),
            (int) ($level['sub'] ?? self::SUB),
        ];
    }

    /** Room-shaped hole in the plan, with a cell of clearance on every side. */
    public static function fits(array $rooms, int $gx, int $gy, int $w, int $h): bool
    {
        foreach ($rooms as $r) {
            if ($gx <= $r['gx'] + $r['w'] && $r['gx'] <= $gx + $w
                && $gy <= $r['gy'] + $r['h'] && $r['gy'] <= $gy + $h) {
                return false;
            }
        }
        return true;
    }

    /**
     * Join every room, then add a few ways round.
     *
     * A nearest-neighbour spanning tree first, which guarantees the level is
     * walkable BY CONSTRUCTION rather than by checking afterwards — this is the
     * same move BattleMapGen makes by never building on a deployment zone, and
     * it is why there is no repair pass here to go wrong.
     *
     * Then `$loops` extra edges between rooms that are near each other but far
     * apart in the tree. A dungeon that is a pure tree is a dungeon where every
     * wrong turn is a dead end and every retreat is the way you came; the loops
     * are what make it a place you can be cut off in.
     */
    private static function joinRooms(int &$rng, array $rooms, int $loops): array
    {
        $n = count($rooms);
        if ($n < 2) {
            return [];
        }
        $edges = [];
        $inTree = [0 => true];
        $out = range(1, $n - 1);

        while ($out) {
            $best = null;
            foreach (array_keys($inTree) as $a) {
                foreach ($out as $bi => $b) {
                    $d = self::planDistance($rooms[$a], $rooms[$b]);
                    if ($best === null || $d < $best['d']) {
                        $best = ['a' => $a, 'b' => $b, 'bi' => $bi, 'd' => $d];
                    }
                }
            }
            $edges[] = ['a' => $best['a'], 'b' => $best['b'], 'door' => self::door($rng)];
            $inTree[$best['b']] = true;
            array_splice($out, $best['bi'], 1);
        }

        // The loops. Candidates are pairs that are close on the plan and not
        // already joined; the closest are taken first so a loop reads as a
        // short cut rather than a corridor across the whole level.
        $pairs = [];
        for ($a = 0; $a < $n; $a++) {
            for ($b = $a + 1; $b < $n; $b++) {
                if (self::joined($edges, $a, $b)) {
                    continue;
                }
                $pairs[] = ['a' => $a, 'b' => $b, 'd' => self::planDistance($rooms[$a], $rooms[$b])];
            }
        }
        usort($pairs, static fn ($p, $q) => $p['d'] <=> $q['d']);
        foreach (array_slice($pairs, 0, max(0, $loops)) as $p) {
            $edges[] = ['a' => $p['a'], 'b' => $p['b'], 'door' => self::door($rng)];
        }
        return $edges;
    }

    /** Centre-to-centre on the coarse plan. */
    private static function planDistance(array $a, array $b): float
    {
        $ax = $a['gx'] + $a['w'] / 2;
        $ay = $a['gy'] + $a['h'] / 2;
        $bx = $b['gx'] + $b['w'] / 2;
        $by = $b['gy'] + $b['h'] / 2;
        return sqrt(($ax - $bx) ** 2 + ($ay - $by) ** 2);
    }

    private static function joined(array $edges, int $a, int $b): bool
    {
        foreach ($edges as $e) {
            if (($e['a'] === $a && $e['b'] === $b) || ($e['a'] === $b && $e['b'] === $a)) {
                return true;
            }
        }
        return false;
    }

    /**
     * What is in the doorway.
     *
     * Flavour, and one rule: a `stuck` door is the only kind that can hide an
     * exit, because a way you have to force is a way you have to find first.
     * Everything else is a label.
     */
    private static function door(int &$rng): string
    {
        return match (self::rint($rng, 1, 10)) {
            1, 2, 3, 4, 5 => 'open',
            6, 7          => 'door',
            8, 9          => 'stuck',
            default       => 'arch',
        };
    }

    /**
     * The party must be able to walk out of the room it arrives in.
     *
     * A `stuck` door is hidden until searched (see `door()` and
     * `DelveEngine::writeExits`), and hidden is the ROOM end of a join only —
     * so a sealed room anywhere else in the level is still enterable, and the
     * party is standing in it when they need to search their way back out.
     * The entrance is the one room where that does not hold: the party lands
     * there having visited nothing, so if every door out of it is stuck the
     * whole floor is unreachable. `endpoints()` picks a graph-diameter room,
     * which is very often a leaf with exactly one edge, so this was not rare —
     * it sealed about one level in seven, and the floor plan went on drawing
     * every room as a click target that answered "There is no way to get there
     * from here."
     *
     * The cheapest door out is opened rather than all of them: one way out of
     * the entrance is all that walkability needs, and a level whose other
     * entrance doors are jammed is still a level with jammed doors in it.
     * Chosen without the rng so that unsealing cannot shift every later roll.
     */
    private static function unsealEntrance(array &$edges, int $entrance): void
    {
        $mine = [];
        foreach ($edges as $i => $e) {
            if ($e['a'] === $entrance || $e['b'] === $entrance) {
                if ($e['door'] !== 'stuck') {
                    return; // already a way out that needs no finding
                }
                $mine[] = $i;
            }
        }
        if ($mine) {
            $edges[$mine[0]]['door'] = 'door';
        }
    }

    /**
     * The two rooms furthest apart in the graph: you come in at one, you go
     * down at the other.
     *
     * Measured in HOPS rather than on the plan, because what matters is how
     * much dungeon is between them, not how far apart they are drawn. A double
     * breadth-first search — furthest from room 0, then furthest from that —
     * which is the standard way to find the long way through a tree and is
     * near enough on a tree with a few loops in it.
     *
     * @return array{0:int, 1:int}
     */
    private static function endpoints(array $rooms, array $edges): array
    {
        if (count($rooms) < 2) {
            return [0, 0];
        }
        $far = static function (int $from) use ($rooms, $edges): array {
            $dist = array_fill(0, count($rooms), -1);
            $dist[$from] = 0;
            $queue = [$from];
            while ($queue) {
                $at = array_shift($queue);
                foreach ($edges as $e) {
                    foreach ([[$e['a'], $e['b']], [$e['b'], $e['a']]] as [$p, $q]) {
                        if ($p === $at && $dist[$q] < 0) {
                            $dist[$q] = $dist[$at] + 1;
                            $queue[] = $q;
                        }
                    }
                }
            }
            $best = $from;
            foreach ($dist as $room => $d) {
                if ($d > $dist[$best]) {
                    $best = $room;
                }
            }
            return [$best, $dist];
        };

        [$a] = $far(0);
        [$b] = $far($a);
        return [$a, $b];
    }

    /**
     * Fill the rooms.
     *
     * The entrance is always empty and the stair room always holds something —
     * neither is a die roll. Walking into a fight before you have taken a step
     * is a bad opening, and a way down that costs nothing is not a way down
     * worth finding.
     */
    private static function stock(int &$rng, array &$rooms, int $entrance, int $stair, bool $boss): void
    {
        $total = 0;
        foreach (self::CONTENTS as $c) {
            $total += $c['weight'];
        }

        foreach ($rooms as $i => $room) {
            if ($i === $entrance) {
                $rooms[$i]['kind'] = 'empty';
                $rooms[$i]['role'] = 'entrance';
                continue;
            }
            if ($i === $stair) {
                $rooms[$i]['kind'] = $boss ? 'boss' : 'hoard';
                $rooms[$i]['role'] = 'stair';
                continue;
            }
            $roll = self::rint($rng, 1, $total);
            foreach (self::CONTENTS as $c) {
                $roll -= $c['weight'];
                if ($roll <= 0) {
                    $rooms[$i]['kind'] = $c['kind'];
                    break;
                }
            }
        }
    }

    /**
     * Put something in the rooms that hold treasure.
     *
     * After stocking, because it reads the kind; before describing, because the
     * description names what is here. Deeper floors fasten and rig more of them
     * — the lock and trap chances climb with depth rather than the kinds
     * changing, so a chest is a chest all the way down and it is the dungeon
     * that gets meaner.
     */
    private static function furnish(int &$rng, array &$rooms, int $depth, string $band): void
    {
        $total = 0;
        foreach (self::FURNISHINGS as $f) {
            $total += $f['weight'];
        }
        // Ten points of each per floor below the first, capped so that the
        // bottom of a deep delve is not a floor of uniformly locked, uniformly
        // rigged boxes — at which point neither fact is information.
        $harder = min(25, 10 * max(0, $depth - 1));

        foreach ($rooms as $i => $room) {
            if (!isset(self::FURNISHED_KINDS[$room['kind'] ?? ''])) {
                continue;
            }
            $roll = self::rint($rng, 1, $total);
            $pick = self::FURNISHINGS[0];
            foreach (self::FURNISHINGS as $f) {
                $roll -= $f['weight'];
                if ($roll <= 0) {
                    $pick = $f;
                    break;
                }
            }
            // Both rolled every time even when the chance is zero, so that the
            // stream a level is made from does not depend on which furnishing
            // came up. A barrel that skipped its lock roll would shift every
            // die after it and make the rest of the floor a different floor.
            $lockRoll = self::rint($rng, 1, 100);
            $trapRoll = self::rint($rng, 1, 100);
            $trapPick = self::rint($rng, 0, count(self::TRAPS[$band]) - 1);
            $trapped = $pick['trap'] > 0 && $trapRoll <= min(85, $pick['trap'] + $harder);
            $rooms[$i]['furnishing'] = [
                'kind'    => $pick['kind'],
                'clause'  => $pick['clause'],
                'locked'  => $pick['lock'] > 0 && $lockRoll <= min(90, $pick['lock'] + $harder),
                // The lid's own difficulty, and it is not the door's. A door
                // is joinery in a frame somebody else built; a strongbox was
                // made to be a strongbox. So the floor's number plus the
                // furnishing's own — a barrel at zero is not locked at all and
                // never reads this, a strongbox is the hardest thing on the
                // level to open without the key.
                'dc'      => 10 + $depth + intdiv((int) $pick['lock'], 20),
                // The trap ITSELF, not a flag saying there is one. It is the
                // same record a passage trap is — key, save, DC, damage, and
                // the two pieces of prose — so FurnishingEngine can fire it
                // through LocationEngine::fireTrapOn and a chest lid does the
                // same damage in the same way as a tripwire. `trapped` stays
                // beside it because a great deal of code only wants the yes or
                // no, and `!== null` is a worse way to ask it.
                'trapped' => $trapped,
                'trap'    => $trapped ? self::TRAPS[$band][$trapPick] : null,
            ];
            // Appended here rather than woven into describe(), because this
            // pass runs after it — the same way the atmosphere clause above is
            // appended. It goes last in the paragraph on purpose: it is the
            // thing a player is about to act on.
            $rooms[$i]['description'] = rtrim((string) ($rooms[$i]['description'] ?? ''))
                . ' ' . $pick['clause'];
        }
    }

    /**
     * Give every room a name and four sentences.
     *
     * WITHOUT REPEATING ITSELF WITHIN A LEVEL, which is the whole difficulty.
     * A weighted draw per room reads fine for two rooms and badly for ten — the
     * player notices the third "grit crunches underfoot" long before they
     * notice the first, and the moment they do, every room in the dungeon
     * becomes furniture. So each table is dealt from rather than sampled: the
     * fragments are shuffled once per level and handed out in order, and only
     * when a table runs dry does it reshuffle and start again. A level with
     * more rooms than a table has entries repeats at most once, and never twice
     * in a row.
     *
     * The shuffle is the same seeded stream everything else uses, so the prose
     * is as reproducible as the layout: seed 4471 always produces the same
     * dungeon, described in the same words.
     */
    private static function describe(int &$rng, array &$rooms, string $profile): void
    {
        $band = self::PROSE[$profile];
        $names = self::deal($rng, self::NAMES[$profile][0]);
        $decks = [
            'shape' => self::deal($rng, $band['shape']),
            'floor' => self::deal($rng, $band['floor']),
            'wall'  => self::deal($rng, $band['wall']),
            'sense' => self::deal($rng, $band['sense']),
        ];
        // What each deck played last, so a reshuffle cannot repeat it.
        $last = ['name' => '', 'shape' => '', 'floor' => '', 'wall' => '', 'sense' => ''];

        foreach ($rooms as $i => $room) {
            // Dealt, never redrawn — see NAMES. Prose below still goes through
            // draw(), because a sentence repeating across a long level is fine
            // and a name repeating is not.
            $name = self::nameDeck($names, (int) $room['id']);

            // The stair and the entrance are named for what they are. A player
            // reading "The Storeroom" on the way out has learned nothing; "The
            // Way Down" is the one label that has to be legible on the chart.
            if ($room['role'] === 'entrance') {
                $name = 'The Way In';
            } elseif ($room['role'] === 'stair') {
                $name = 'The Way Down';
            }

            $shape = self::draw($rng, $decks['shape'], $band['shape'], $last['shape']);
            $floor = self::draw($rng, $decks['floor'], $band['floor'], $last['floor']);
            $wall  = self::draw($rng, $decks['wall'], $band['wall'], $last['wall']);
            $sense = self::draw($rng, $decks['sense'], $band['sense'], $last['sense']);
            $hint  = self::PROSE_KIND[$room['kind']] ?? self::PROSE_KIND['empty'];
            $hint  = $hint[self::rint($rng, 0, count($hint) - 1)];

            $rooms[$i]['name'] = $name;
            $rooms[$i]['description'] = "{$shape}. {$floor} {$wall} {$sense} {$hint}";
        }
    }

    /**
     * The name for one room, off a deck that is dealt once.
     *
     * By index rather than by shifting, so the name a room gets does not
     * depend on how many rooms were named before it — which keeps this a pure
     * function of the shuffled deck and the room, and means it cannot go wrong
     * if the caller ever names rooms out of order.
     *
     * The fallback can only fire if a profile asks for more rooms than its
     * name table holds. It is numbered rather than wrapped, because a level
     * with "The Guard Room" twice on it is a bug that reads as a map fault at
     * play, and "The Guard Room II" is one that reads as a table too short —
     * which is what it is, and what the test asserts against.
     */
    private static function nameDeck(array $deck, int $index): string
    {
        if ($index < count($deck)) {
            return (string) $deck[$index];
        }
        $n = intdiv($index, count($deck)) + 1;
        return $deck[$index % count($deck)] . ' ' . str_repeat('I', $n);
    }

    /** A shuffled copy of a table, to be dealt from. Fisher-Yates, seeded. */
    private static function deal(int &$rng, array $table): array
    {
        $deck = array_values($table);
        for ($i = count($deck) - 1; $i > 0; $i--) {
            $j = self::rint($rng, 0, $i);
            [$deck[$i], $deck[$j]] = [$deck[$j], $deck[$i]];
        }
        return $deck;
    }

    /**
     * Take the next card; reshuffle when the deck runs out.
     *
     * `$last` is carried so that a reshuffle cannot deal the card that was just
     * played. Without it the guarantee is only "at most one repeat per table",
     * and the one case that actually reads as broken — the same sentence in two
     * rooms in a row — is exactly the case a fresh shuffle makes likely, since
     * every card is equally free to come up first.
     */
    private static function draw(int &$rng, array &$deck, array $table, string &$last): string
    {
        if (!$deck) {
            $deck = self::deal($rng, $table);
            if (count($deck) > 1 && $deck[0] === $last) {
                $swap = self::rint($rng, 1, count($deck) - 1);
                [$deck[0], $deck[$swap]] = [$deck[$swap], $deck[0]];
            }
        }
        $last = (string) array_shift($deck);
        return $last;
    }

    // =======================================================================
    // The drawn plan
    // =======================================================================

    /**
     * The level as something you can draw: room rectangles and corridors.
     *
     * A pure function of a generated level — no rng, no database, no state.
     * That matters because nothing stores this: DelveEngine regenerates the
     * level from the seed whenever the chart asks for it, exactly as status()
     * already regenerates it to find the stair. A plan that consulted the rng
     * would come out differently on the second call and the map would change
     * shape under the party between two screens.
     *
     * Everything returned is in the chart's 0-100 by 0-75 field, so ui-map.js
     * draws it in the coordinates it already uses and needs no conversion of
     * its own. The client does no geometry here, for the reason CLAUDE.md
     * gives about combat: a second copy of a rule in JavaScript is a copy that
     * drifts.
     *
     * A corridor is a dogleg — out of one room, one right-angle turn, into the
     * other — because that is what reads as a dungeon passage. Which axis it
     * takes first is decided by the parity of the two room ids rather than by
     * a roll, so the shape is a property of the level and not of when it was
     * asked for.
     *
     * @param  array $level as returned by generate()
     * @return array{rooms: list<array>, corridors: list<array>}
     */
    public static function plan(array $level): array
    {
        [$gw, $gh, $sub] = self::gridOf($level);
        $rooms = [];
        foreach ($level['rooms'] as $r) {
            // The room's own footprint, exactly. Not inset and not grown.
            //
            // BOTH WERE TRIED AND BOTH ARE WRONG, for opposite reasons worth
            // recording. An inset — a tenth of a cell was shipped — is taken
            // off both sides, so it costs every dimension twice over: a 1-cell
            // side lost a fifth of itself while a 2-cell side barely noticed,
            // and the dungeon's small rooms were drawn as slots.
            //
            // An outset looks like the obvious answer to "the rooms are small"
            // and is worse. Corridors run centre to centre, so a fair number of
            // them run flush along the outside wall of a room they do not join.
            // At zero that reads as a passage past a wall; grown by anything at
            // all — a tenth is enough — it becomes a passage THROUGH the corner
            // of somebody's chamber with no door at either end, and the sweep's
            // count of those jumps from 1.8% of levels to 8.7% and stays there.
            // The room size came from the grid instead; see GRID_W.
            [$x1, $y1] = self::project($r['gx'], $r['gy'], $gw, $gh);
            [$x2, $y2] = self::project($r['gx'] + $r['w'], $r['gy'] + $r['h'], $gw, $gh);
            $rooms[] = [
                'id'   => (int) $r['id'],
                'x'    => $x1,
                'y'    => $y1,
                'w'    => round($x2 - $x1, 2),
                'h'    => round($y2 - $y1, 2),
                'role' => $r['role'],
                // The chart draws the same furnishing the raster stands up and
                // the prose names, so the two maps and the paragraph agree
                // about what is in the room. The KIND only: whether it is
                // locked or trapped is something a party finds out by trying
                // it, and a plan that spelled it out would be the chart
                // answering a question the room is asking.
                'furnishing' => isset($r['furnishing'])
                    ? (string) $r['furnishing']['kind'] : null,
            ];
        }
        $rect = array_column($rooms, null, 'id');

        $routes = self::routes($level);
        $corridors = [];
        foreach ($level['corridors'] ?? [] as $e) {
            $id = (int) $e['id'];
            if (!isset($routes[$id])) {
                // The router found nowhere to put it. Only ever a loop edge —
                // routes() is measured against the sweep on exactly this — so
                // the level stays whole and the chart draws one fewer way
                // round. DelveEngine writes passages from what is here, so the
                // graph and the drawing lose it together.
                continue;
            }

            // The carved run, in the chart's field. The two room tiles at the
            // ends come first and last so clipEnds() has something inside each
            // rectangle to cut back to — the same trim it has always made, on
            // a line that now goes where the floor does.
            $r = $routes[$id];
            $points = [];
            foreach (array_merge([$r['from']], $r['run'], [$r['to']]) as $tile) {
                $points[] = self::tilePoint($tile, $gw, $gh, $sub);
            }
            $points = self::straighten($points);
            $points = self::clipEnds($points, $rect[(int) $e['a']], $rect[(int) $e['b']]);
            if (count($points) < 2) {
                continue;
            }

            $corridors[] = [
                'id'     => $id,
                'a'      => (int) $e['a'],
                'b'      => (int) $e['b'],
                'door'   => $e['door'],
                'points' => $points,
                // Where a door is drawn: one glyph on each threshold. `at` is
                // the wall of the room the corridor arrives at and `at_a` the
                // wall it leaves — one doorway, two rooms it shows in, exactly
                // as the exits are written twice in the graph.
                'at'     => $points[count($points) - 1],
                'at_a'   => $points[0],
                // Where the passage IS, for the chart to hang its node on —
                // halfway along the run by length, not the midpoint of the two
                // ends, so a dogleg's marker sits in the passage rather than
                // in the corner it cuts.
                'mid'    => self::midpoint($points),
                // The trap KEY only — enough to draw a mark. Whether the party
                // gets to see it is per-party knowledge and planFor()'s to
                // decide; the spec that fires lives on the passage row.
                'trap'   => isset($e['trap']) ? $e['trap']['key'] : null,
            ];
        }

        // The ten-foot grid the level is actually built on, in the chart's
        // own units, so the renderer can rule the page without owning a second
        // copy of the projection. `sub` is subtiles per cell, so one TILE is
        // 1/sub of a cell — 1/1 for a level from the map service, whose cells
        // ARE tiles, and 1/3 for this generator's own.
        //
        // Measured through project() rather than derived beside it. The header
        // promises the conversion is written once and nothing downstream
        // repeats it; computing a pitch as (VIEW_W - 16) / ($gw * $sub) here
        // would be exactly the second copy it warns about.
        // Measured across the WHOLE grid and divided, not taken from one
        // tile. project() rounds its answer to two places, which on a single
        // tile is a rounding of the pitch itself — 84/72 comes back as 1.17
        // against a true 1.166667 — and the renderer then multiplies that
        // error by a column index. Over the full span the rounding lands once,
        // on a number near 92, and divides away to nothing.
        [$ox, $oy] = self::project(0, 0, $gw, $gh);
        [$fx, $fy] = self::project($gw, $gh, $gw, $gh);
        $tilesX = max(1, $gw * $sub);
        $tilesY = max(1, $gh * $sub);

        return [
            'rooms'     => $rooms,
            'corridors' => $corridors,
            'grid'      => [
                'x'  => $ox,
                'y'  => $oy,
                // Six places, not the two the chart rounds coordinates to.
                // The renderer multiplies this pitch by a column index up to
                // the width of the level, so an error in it is multiplied too:
                // at four places, 84/72 rounds to 1.1700 against a true
                // 1.166667, and by the far side of a 72-column floor the lines
                // have walked a fifth of a square off the rooms they are
                // supposed to be measuring.
                'dx' => round(($fx - $ox) / $tilesX, 6),
                'dy' => round(($fy - $oy) / $tilesY, 6),
            ],
        ];
    }

    /**
     * Drop the points a straight run does not need.
     *
     * The raster hands back every tile a passage stands on, which as a polyline
     * is a point per ten feet and mostly collinear. The chart wants the corners
     * and nothing else — and so does clipEnds(), whose crossing test walks
     * segments rather than points and would otherwise be handed dozens of them.
     *
     * @param  list<array{0:float,1:float}> $points
     * @return list<array{0:float,1:float}>
     */
    private static function straighten(array $points): array
    {
        $out = [];
        foreach ($points as $i => $p) {
            if ($i > 0 && $i < count($points) - 1) {
                [$px, $py] = $points[$i - 1];
                [$nx, $ny] = $points[$i + 1];
                $straight = (abs($px - $p[0]) < 1e-9 && abs($nx - $p[0]) < 1e-9)
                    || (abs($py - $p[1]) < 1e-9 && abs($ny - $p[1]) < 1e-9);
                if ($straight) {
                    continue;
                }
            }
            $out[] = $p;
        }
        return $out;
    }

    /**
     * The point half the run's length along a polyline.
     *
     * Not the average of the two ends: a dogleg's ends average to a point off
     * the passage entirely, usually inside the corner it turns. This walks the
     * segments and stops halfway, so the marker is always somewhere the party
     * could actually be standing.
     *
     * @param  list<array{0:float,1:float}> $points
     * @return array{0:float,1:float}
     */
    private static function midpoint(array $points): array
    {
        $total = 0.0;
        for ($i = 1; $i < count($points); $i++) {
            $total += abs($points[$i][0] - $points[$i - 1][0])
                + abs($points[$i][1] - $points[$i - 1][1]);
        }
        if ($total <= 0.0) {
            return [round($points[0][0], 2), round($points[0][1], 2)];
        }

        $want = $total / 2;
        for ($i = 1; $i < count($points); $i++) {
            $len = abs($points[$i][0] - $points[$i - 1][0])
                + abs($points[$i][1] - $points[$i - 1][1]);
            if ($len >= $want) {
                $k = $len > 0 ? $want / $len : 0;
                return [
                    round($points[$i - 1][0] + ($points[$i][0] - $points[$i - 1][0]) * $k, 2),
                    round($points[$i - 1][1] + ($points[$i][1] - $points[$i - 1][1]) * $k, 2),
                ];
            }
            $want -= $len;
        }
        $last = $points[count($points) - 1];
        return [round($last[0], 2), round($last[1], 2)];
    }

    /**
     * Cut a polyline back to where it leaves the first rect and enters the last.
     *
     * Every segment is axis-aligned, which is what makes this arithmetic
     * rather than geometry: a crossing is one coordinate solved on a segment
     * that only varies in one coordinate.
     *
     * @param  list<array{0:float,1:float}> $points
     * @return list<array{0:float,1:float}>
     */
    private static function clipEnds(array $points, array $from, array $to): array
    {
        $exit = self::crossing($points, $from);
        $points = array_reverse($points);
        $enter = self::crossing($points, $to);
        $points = array_reverse($points);

        if ($exit === null || $enter === null) {
            return [];
        }
        // Drop the interior points that fall inside either room, then cap the
        // run with the two wall crossings.
        $mid = [];
        foreach ($points as $p) {
            if (!self::inRect($p, $from) && !self::inRect($p, $to)) {
                $mid[] = $p;
            }
        }
        return array_merge([$exit], $mid, [$enter]);
    }

    /** Where a polyline starting inside $rect first leaves it. */
    private static function crossing(array $points, array $rect): ?array
    {
        for ($i = 0; $i < count($points) - 1; $i++) {
            [$x1, $y1] = $points[$i];
            [$x2, $y2] = $points[$i + 1];
            if (!self::inRect($points[$i], $rect)) {
                continue;
            }
            if (self::inRect($points[$i + 1], $rect)) {
                continue;   // wholly inside; the crossing is further along
            }
            if (abs($y2 - $y1) < 1e-9) {          // horizontal run
                $x = $x2 > $x1 ? $rect['x'] + $rect['w'] : $rect['x'];
                return [round($x, 2), round($y1, 2)];
            }
            $y = $y2 > $y1 ? $rect['y'] + $rect['h'] : $rect['y'];
            return [round($x1, 2), round($y, 2)];
        }
        return null;
    }

    private static function inRect(array $p, array $rect): bool
    {
        return $p[0] >= $rect['x'] - 1e-9 && $p[0] <= $rect['x'] + $rect['w'] + 1e-9
            && $p[1] >= $rect['y'] - 1e-9 && $p[1] <= $rect['y'] + $rect['h'] + 1e-9;
    }

    // =======================================================================
    // The raster
    //
    // Where a corridor actually runs, in plan cells, and what the level looks
    // like tile by tile. Two functions and their helpers, and the first of them
    // is the source of a corridor's shape for BOTH drawings: plan() projects
    // these cells for the chart, and tiles() carves them for the first-person
    // view. That is not tidiness. A router that avoided a chamber while the
    // chart went on drawing the old line through it would be two maps of one
    // place disagreeing, and the disagreement would show as a wall where the
    // map says there is a door.
    //
    // RNG-FREE, all of it, like everything below plan(). The golden hash in
    // tools/test_dungeon.php pins generate()'s call sequence, and a rolled
    // level has to keep rebuilding byte-identically from its seed for as long
    // as somebody's delve is stored as two numbers.
    // =======================================================================

    /**
     * The cells each corridor runs through, keyed by corridor id.
     *
     * A corridor's route is a shortest path over the plan grid from any cell of
     * one room to any cell of the other, THROUGH CELLS NO ROOM OWNS. That last
     * clause is the whole point of doing this properly rather than choosing
     * between two doglegs. Centre-to-centre doglegs put a passage through a
     * chamber it does not join on about one level in forty even after picking
     * the better of the two, which was tolerable while a corridor was a
     * hairline drawn behind a box — and is a doorless hole in somebody's wall
     * the moment the level is carved into tiles and looked at from inside.
     *
     * ROUTED IN TILES, NOT IN PLAN CELLS, and that is the one decision here
     * worth arguing. Cells are what rooms are placed on, so routing on them is
     * the obvious first thought and it was the first draft. It does not work:
     * a cell is the whole width of the gap between two rooms, so every corridor
     * running the same way between the same two ranks of chambers is forced
     * onto one lane, and two passages ended up sharing floor on 38% of levels —
     * measured, not guessed. On tiles they pass each other with rock between,
     * and the only collisions left are the genuine pinches where the plan gives
     * a one-cell gap and there is nowhere else for a second corridor to be.
     *
     * A corridor tile may touch a room ONLY at the two ends of the run. That is
     * what stops a passage opening a doorless hole in a chamber it does not
     * join — the fault the two-dogleg guess left on one level in forty — and it
     * is stated as a passability rule rather than checked afterwards, so there
     * is no repair pass to go wrong.
     *
     * Corridors are routed in the order they were joined. Each one refuses
     * every tile an earlier corridor took, and pays ADJACENT_COST to run beside
     * one — the two halves of "a place belongs to one location, but a thin wall
     * between two passages is an ordinary thing for a dungeon to have".
     *
     * @param  array $level as returned by generate()
     * @return array<int, array{run: list<int>, from: int, to: int}>
     *         corridor id => the tile indices of its floor, and the two room
     *         tiles its doors open onto
     */
    public static function routes(array $level): array
    {
        [$gw, $gh, $sub] = self::gridOf($level);
        $tw = $sub * $gw + 2;
        [$roomAt, $near, $centre] = self::roomTiles($level['rooms'], $gw, $gh, $sub);
        $taken = [];    // tiles an earlier corridor stands on: never enterable
        $beside = [];   // tiles next to one: enterable, at a price
        $out = [];

        foreach ($level['corridors'] ?? [] as $e) {
            $run = self::route(
                $roomAt,
                $near,
                $centre,
                $taken,
                $beside,
                (int) $e['a'],
                (int) $e['b'],
                $tw
            );
            if ($run === null) {
                continue;
            }
            $from = self::roomSideOf($roomAt, $run[0], (int) $e['a'], $tw);
            $to = self::roomSideOf($roomAt, $run[count($run) - 1], (int) $e['b'], $tw);
            if ($from === null || $to === null) {
                continue;
            }
            $out[(int) $e['id']] = ['run' => $run, 'from' => $from, 'to' => $to];

            foreach ($run as $i) {
                $taken[$i] = true;
                foreach (self::steps($tw) as $off) {
                    $beside[$i + $off] = true;
                }
            }
        }
        return $out;
    }

    /** Tile-index offsets for N, E, S, W. The border makes them always safe. */
    private static function steps(?int $tw = null): array
    {
        $tw ??= self::TILE_W;
        return [-$tw, 1, $tw, -1];
    }

    /**
     * Which room each tile is in, and which room each rock tile lies beside.
     *
     * `near` is the interesting half: -1 for rock with no room beside it, a
     * room id for rock touching exactly one, and -2 for rock a passage may not
     * run in at all. A corridor may start on a tile whose `near` is the room it
     * leaves, finish on one whose `near` is the room it arrives at, and pass
     * only through -1. Three integers, and the whole "no doorless holes" rule.
     *
     * -2 IS BOTH "BESIDE TWO ROOMS" AND "ON THE BORDER", which reads like two
     * things sharing a value and is one: neither is somewhere a passage may be.
     * The border earns it the harder way. It was left at -1 while `near` was
     * computed over the interior only, so the outermost ring looked like open
     * rock with nothing beside it — and a room placed at cell 0 has its wall ON
     * that ring, so corridors ran the length of a chamber with no door and no
     * rock between. That is the exact fault this whole routing rule exists to
     * prevent, hiding in the one place the loop did not look.
     *
     * @return array{0: list<int>, 1: list<int>, 2: array<int,array{0:int,1:int}>}
     *         roomAt (-1 for rock), near, and each room's centre tile as [x, y]
     */
    private static function roomTiles(array $rooms, ?int $gw = null, ?int $gh = null, ?int $sub = null): array
    {
        $gw ??= self::GRID_W;
        $gh ??= self::GRID_H;
        $sub ??= self::SUB;
        $tw = $sub * $gw + 2;
        $th = $sub * $gh + 2;
        $n = $tw * $th;
        $roomAt = array_fill(0, $n, -1);
        $centre = [];

        foreach ($rooms as $r) {
            $id = (int) $r['id'];
            $x0 = $sub * (int) $r['gx'] + 1;
            $x1 = $sub * ((int) $r['gx'] + (int) $r['w']);
            $y0 = $sub * (int) $r['gy'] + 1;
            $y1 = $sub * ((int) $r['gy'] + (int) $r['h']);
            for ($y = $y0; $y <= $y1; $y++) {
                for ($x = $x0; $x <= $x1; $x++) {
                    $roomAt[$y * $tw + $x] = $id;
                }
            }
            $centre[$id] = [intdiv($x0 + $x1, 2), intdiv($y0 + $y1, 2)];
        }

        $near = array_fill(0, $n, -1);
        for ($i = 0; $i < $n; $i++) {
            $x = $i % $tw;
            $y = intdiv($i, $tw);
            if ($x === 0 || $y === 0 || $x === $tw - 1 || $y === $th - 1) {
                $near[$i] = -2;
                continue;
            }
            if ($roomAt[$i] >= 0) {
                continue;
            }
            foreach (self::steps($tw) as $off) {
                $r = $roomAt[$i + $off];
                if ($r < 0) {
                    continue;
                }
                $near[$i] = $near[$i] === -1 || $near[$i] === $r ? $r : -2;
            }
        }
        return [$roomAt, $near, $centre];
    }

    /** The tile of room $room that a door on $tile opens onto. */
    private static function roomSideOf(array $roomAt, int $tile, int $room, ?int $tw = null): ?int
    {
        $tw ??= self::TILE_W;
        foreach (self::steps($tw) as $off) {
            if (($roomAt[$tile + $off] ?? -1) === $room) {
                return $tile + $off;
            }
        }
        return null;
    }

    /**
     * One corridor's route: cheapest path from room $a's cells to room $b's.
     *
     * Dijkstra over (cell, direction) rather than over cells, because the cost
     * of arriving somewhere depends on which way you were going when you did —
     * that is what makes TURN_COST expressible at all. The state space is 9x7x4
     * and every cost is a small integer, so the queue is a row of buckets
     * indexed by cost (Dial's) rather than a heap: exact, allocation-free in the
     * inner loop, and deterministic without a tie-break rule, because states
     * come out of a bucket in the order they went in.
     *
     * Room $a's cells are all sources at zero, in all four directions, so the
     * first step out of a chamber pays no turn whichever wall it leaves by —
     * and since they start settled, no path can re-enter the room it began in.
     *
     * Dijkstra over (tile, direction) rather than over tiles, because what a
     * step costs depends on which way you were going when you took it — that
     * is what makes TURN_COST expressible at all. Costs are small integers, so
     * the queue is a row of buckets indexed by cost (Dial's) rather than a
     * heap: exact, and deterministic with no tie-break rule to write, because
     * states leave a bucket in the order they entered it.
     *
     * Every tile beside room $a starts settled at zero, facing all four ways,
     * so the first step out pays no turn whichever wall it leaves by and the
     * router picks the doorway rather than a rule guessing at it. They also
     * cannot be re-entered, since only `near === -1` is passable in the middle.
     *
     * @param  list<int>       $roomAt  tile => room id, -1 for rock
     * @param  list<int>       $near    tile => the one room beside it, -1 none, -2 never
     * @param  array<int,array{0:int,1:int}> $centre room id => its centre tile
     * @param  array<int,true> $taken  tiles an earlier corridor stands on
     * @param  array<int,true> $beside tiles next to one
     * @return list<int>|null  the run, door tile first and door tile last
     */
    private static function route(
        array $roomAt,
        array $near,
        array $centre,
        array $taken,
        array $beside,
        int $a,
        int $b,
        ?int $tw = null
    ): ?array {
        $tw ??= self::TILE_W;
        $dist = [];
        $prev = [];
        $buckets = [];
        $top = 0;

        foreach ($near as $i => $besideRoom) {
            if ($besideRoom !== $a || $roomAt[$i] >= 0 || isset($taken[$i])) {
                continue;
            }
            $start = self::DOOR_COST * self::doorOffset($roomAt, $centre, $i, $a, $tw)
                + (isset($beside[$i]) ? self::ADJACENT_COST : 0);
            for ($d = 0; $d < 4; $d++) {
                $k = ($i << 2) | $d;
                $dist[$k] = $start;
                $buckets[$start][] = $k;
            }
            $top = $start > $top ? $start : $top;
        }
        if (!$buckets) {
            return null;
        }

        $offs = self::steps($tw);

        for ($cost = 0; $cost <= $top; $cost++) {
            if (!isset($buckets[$cost])) {
                continue;
            }
            // count() is re-read each pass on purpose: a relaxation never
            // pushes into the bucket being drained (every move costs at least
            // one), so the list only grows from later costs.
            for ($qi = 0; $qi < count($buckets[$cost]); $qi++) {
                $k = $buckets[$cost][$qi];
                if (($dist[$k] ?? PHP_INT_MAX) !== $cost) {
                    continue;   // stale: reached again more cheaply since
                }
                $d = $k & 3;
                $i = $k >> 2;

                if ($near[$i] === $b) {
                    return self::unwind($prev, $k);
                }
                for ($nd = 0; $nd < 4; $nd++) {
                    $j = $i + $offs[$nd];
                    if (($roomAt[$j] ?? 0) >= 0) {
                        continue;   // off the border, or into a chamber
                    }
                    $besideRoom = $near[$j];
                    if ($besideRoom !== -1 && $besideRoom !== $b) {
                        continue;   // alongside a room this passage does not join
                    }
                    if (isset($taken[$j])) {
                        continue;   // another passage is standing there
                    }
                    $step = $cost + 1
                        + ($nd === $d ? 0 : self::TURN_COST)
                        + (isset($beside[$j]) ? self::ADJACENT_COST : 0)
                        // The far doorway's offset is charged as the cost of
                        // arriving at it, not added once the goal is popped:
                        // a penalty applied after settling is a penalty
                        // Dijkstra never got to weigh against the alternatives.
                        + ($besideRoom === $b ? self::DOOR_COST * self::doorOffset($roomAt, $centre, $j, $b, $tw) : 0);
                    $nk = ($j << 2) | $nd;
                    if (($dist[$nk] ?? PHP_INT_MAX) <= $step) {
                        continue;
                    }
                    $dist[$nk] = $step;
                    $prev[$nk] = $k;
                    $buckets[$step][] = $nk;
                    $top = $step > $top ? $step : $top;
                }
            }
            unset($buckets[$cost]);
        }
        return null;
    }

    /**
     * How far along its wall a doorway sits from the middle of that wall.
     *
     * Measured across the wall, never through it: a door on a chamber's east
     * side is off-centre by how far north or south of the middle it is, and its
     * distance east means nothing. Which wall it is on is read from where the
     * room is, so no side has to be worked out twice.
     */
    private static function doorOffset(array $roomAt, array $centre, int $tile, int $room, ?int $tw = null): int
    {
        $tw ??= self::TILE_W;
        if (!isset($centre[$room])) {
            return 0;
        }
        [$cx, $cy] = $centre[$room];
        foreach (self::steps($tw) as $k => $off) {
            if (($roomAt[$tile + $off] ?? -1) !== $room) {
                continue;
            }
            // steps() is N, E, S, W; east and west are the upright walls.
            return $k === 1 || $k === 3
                ? abs(intdiv($tile, $tw) - $cy)
                : abs($tile % $tw - $cx);
        }
        return 0;
    }

    /** Walk a settled state back to its source, as tile indices. */
    private static function unwind(array $prev, int $k): array
    {
        $run = [];
        while (true) {
            $run[] = $k >> 2;
            if (!isset($prev[$k])) {
                break;
            }
            $k = $prev[$k];
        }
        return array_reverse($run);
    }

    /** 0 N, 1 E, 2 S, 3 W — from one tile index to an orthogonal neighbour. */
    private static function dirTo(int $from, int $to): int
    {
        $step = $to - $from;
        if ($step === 1) {
            return 1;
        }
        if ($step === -1) {
            return 3;
        }
        return $step > 0 ? 2 : 0;
    }

    /**
     * A tile's centre in the chart's field.
     *
     * The raster is a plain integer sub-division BELOW the plan, so a tile's
     * centre is a plan coordinate and project() converts it — which keeps that
     * function what its own comment promises, the only place the two grids meet.
     * The -1 is the border; see TILE_W.
     *
     * @return array{0:float,1:float}
     */
    public static function tilePoint(int $tile, ?int $gw = null, ?int $gh = null, ?int $sub = null): array
    {
        $gw ??= self::GRID_W;
        $gh ??= self::GRID_H;
        $sub ??= self::SUB;
        $tw = $sub * $gw + 2;
        $x = $tile % $tw;
        $y = intdiv($tile, $tw);
        return self::project(($x - 0.5) / $sub, ($y - 0.5) / $sub, $gw, $gh);
    }

    /**
     * The level as ten-foot tiles: what is rock, what is floor, whose it is.
     *
     * WALLS ARE FACES, NOT TILES. A tile is open or it is not, and a door lives
     * on the face between the last tile of a passage and the first tile of the
     * chamber it opens into — recorded once, on the passage's side, with the
     * direction it is looked at through. That is the model the Gold Box games
     * drew and it is the one a first-person view wants: the renderer walks the
     * cells in front of the party and asks each one what is on its faces.
     *
     * Pure and free of the database, so tools/test_dungeon.php can carve
     * thousands of levels and flood-fill every one of them. It knows nothing of
     * location ids; DelveEngine maps `owner` onto rows and censors the result
     * through the same fog() the chart uses, which is why fog is not mentioned
     * anywhere in this file.
     *
     * @param  array $level as returned by generate()
     * @return array{
     *   w:int, h:int, sub:int,
     *   solid: list<list<bool>>,
     *   owner: list<list<array{0:string,1:int}|null>>,
     *   doors: list<array{x:int,y:int,dir:int,kind:string,corridor:int}>,
     *   stairs: list<array{x:int,y:int,dir:string,room:int}>,
     *   spines: array{room: array<int,array{0:int,1:int}>, corridor: array<int,array{0:int,1:int}>},
     *   props: list<array{tile:int, kind:string, room:int}>
     *   shared: int
     * }
     */
    public static function tiles(array $level): array
    {
        // The lattice this level is drawn on, rather than the one every level
        // used to be drawn on. See gridOf().
        [$gw, $gh, $sub] = self::gridOf($level);
        $tw = $sub * $gw + 2;
        $th = $sub * $gh + 2;

        $n = $tw * $th;
        $solid = array_fill(0, $n, true);
        $owner = array_fill(0, $n, null);
        $spines = ['room' => [], 'corridor' => []];
        $props = [];

        foreach ($level['rooms'] as $r) {
            $id = (int) $r['id'];
            $x0 = $sub * (int) $r['gx'] + 1;
            $x1 = $sub * ((int) $r['gx'] + (int) $r['w']);
            $y0 = $sub * (int) $r['gy'] + 1;
            $y1 = $sub * ((int) $r['gy'] + (int) $r['h']);

            for ($y = $y0; $y <= $y1; $y++) {
                for ($x = $x0; $x <= $x1; $x++) {
                    $i = $y * $tw + $x;
                    $solid[$i] = false;
                    $owner[$i] = ['room', $id];
                }
            }
            // The middle of the chamber, which is where a party arriving from
            // anywhere is put down. intdiv on both bounds, so an even-sided
            // room takes the lower of its two middles rather than a half tile.
            $spines['room'][$id] = intdiv($y0 + $y1, 2) * $tw + intdiv($x0 + $x1, 2);

            // Where a furnishing stands, if this room has one.
            //
            // A CORNER, NOT THE MIDDLE — the middle is the spine, which is where
            // a party is put down when they arrive, and standing them inside
            // the chest would be a picture of a party in a box. The far corner
            // from the door is also where anybody actually puts a strongbox.
            // Derived from the room's own bounds rather than rolled, so it
            // costs the level's random stream nothing and a stored level and a
            // regenerated one agree about it.
            if (isset($r['furnishing'])) {
                $props[] = [
                    'tile' => $y1 * $tw + $x1,
                    'kind' => (string) $r['furnishing']['kind'],
                    'room' => $id,
                ];
            }
        }

        $routes = self::routes($level);
        $doors = [];
        $shared = 0;

        foreach ($level['corridors'] ?? [] as $e) {
            $id = (int) $e['id'];
            if (!isset($routes[$id])) {
                continue;
            }
            $run = $routes[$id]['run'];

            foreach ($run as $i) {
                if (!$solid[$i]) {
                    $shared++;   // a pinch: another passage is already here
                    continue;
                }
                $solid[$i] = false;
                $owner[$i] = ['corridor', $id];
            }

            // A threshold is a fact about both sides of itself, so each is
            // written twice — the same doubling location_exits has, and for the
            // same reason. Standing in the chamber you have to see the door
            // and be able to walk through it; standing in the passage, the
            // same. Four records per corridor, two doorways.
            $kind = (string) $e['door'];
            $ends = [
                [$run[0], $routes[$id]['from'], (int) $e['a']],
                [$run[count($run) - 1], $routes[$id]['to'], (int) $e['b']],
            ];
            foreach ($ends as [$hall, $chamber, $room]) {
                $doors[] = [
                    'tile' => $hall,
                    'dir' => self::dirTo($hall, $chamber),
                    'kind' => $kind,
                    'from' => ['corridor', $id],
                    'to' => ['room', $room],
                ];
                $doors[] = [
                    'tile' => $chamber,
                    'dir' => self::dirTo($chamber, $hall),
                    'kind' => $kind,
                    'from' => ['room', $room],
                    'to' => ['corridor', $id],
                ];
            }
            $spines['corridor'][$id] = $run[intdiv(count($run) - 1, 2)];
        }

        // The two stairs, on the spines of the rooms that hold them — the same
        // two roles ui-map.js draws its shortening ticks for.
        $stairs = [];
        foreach ([['up', (int) $level['entrance']], ['down', (int) $level['stair']]] as [$dir, $room]) {
            if (isset($spines['room'][$room])) {
                $stairs[] = ['tile' => $spines['room'][$room], 'dir' => $dir, 'room' => $room];
            }
        }

        return [
            'w' => $tw,
            'h' => $th,
            'sub' => $sub,
            'solid' => $solid,
            'owner' => $owner,
            'doors' => $doors,
            'walls' => self::partitions($owner, $doors, $tw),
            'stairs' => $stairs,
            'props'  => $props,
            'spines' => $spines,
            'shared' => $shared,
        ];
    }

    /**
     * The thin walls: faces between two floor tiles that are not a way through.
     *
     * ADJACENT_COST buys the router a wide berth round other passages and does
     * not always get one — on about one level in twenty two corridors squeeze
     * past each other with no rock left between them. Without this they would
     * be two abutting floor tiles, which in a raster means a hole: the
     * first-person view would draw an opening into a passage the exit graph has
     * no exit to, and a party would walk at it and be refused.
     *
     * So the face carries a wall, which is what graph paper has always done
     * with a partition too thin to draw as rock.
     *
     * WRITTEN FROM BOTH SIDES, like the doorways and for a harder reason than
     * symmetry. The renderer asks what is on the face between the tile it is
     * standing on and the next one along, by tile and direction; a partition
     * recorded only on the lower tile is invisible to anybody approaching it
     * from the other one, and `faceOf()` falls through to "is there floor over
     * there" and answers open. So the wall would be a wall from the west and a
     * doorway from the east, which is worse than not having it.
     *
     * @param  list<array{0:string,1:int}|null> $owner
     * @param  list<array{tile:int,dir:int,kind:string}> $doors
     * @return list<array{tile:int,dir:int}>
     */
    private static function partitions(array $owner, array $doors, ?int $tw = null): array
    {
        $tw ??= self::TILE_W;
        // A doorway is a face that IS a way through. Both sides are already in
        // the list — see where it is built — so there is nothing to mirror.
        $ways = [];
        foreach ($doors as $d) {
            $ways[($d['tile'] << 2) | $d['dir']] = true;
        }

        $walls = [];
        // East and south name every face exactly once; each one is then
        // recorded again from the tile on its other side.
        foreach ([1 => 1, 2 => $tw] as $dir => $off) {
            foreach ($owner as $i => $o) {
                if ($o === null) {
                    continue;
                }
                $n = $owner[$i + $off] ?? null;
                if ($n === null || $n === $o || isset($ways[($i << 2) | $dir])) {
                    continue;
                }
                $walls[] = ['tile' => $i, 'dir' => $dir];
                $walls[] = ['tile' => $i + $off, 'dir' => ($dir + 2) % 4];
            }
        }
        return $walls;
    }

    // =======================================================================
    // Reading a level back
    // =======================================================================

    /**
     * Every room reachable from the entrance.
     *
     * The test's connectivity check, and DelveEngine's sanity check before it
     * writes anything. Kept here rather than reusing BattleGrid::reachable(),
     * which is bound to the 16x12 tactical board by its own constants and knows
     * about terrain costs and bodies — none of which mean anything on a plan of
     * rooms.
     *
     * @return array<int,true> room ids
     */
    public static function reachable(array $level): array
    {
        $seen = [$level['entrance'] => true];
        $queue = [$level['entrance']];
        while ($queue) {
            $at = array_shift($queue);
            foreach ($level['edges'] as $e) {
                foreach ([[$e['a'], $e['b']], [$e['b'], $e['a']]] as [$p, $q]) {
                    if ($p === $at && !isset($seen[$q])) {
                        $seen[$q] = true;
                        $queue[] = $q;
                    }
                }
            }
        }
        return $seen;
    }

    /** Whether every room can be walked to, and the stair among them. */
    public static function isWalkable(array $level): bool
    {
        $seen = self::reachable($level);
        return count($seen) === count($level['rooms']) && isset($seen[$level['stair']]);
    }

    // =======================================================================
    // Randomness
    //
    // splitmix32, carried in an argument. Copied deliberately rather than
    // shared with BattleMapGen: the two generators must be free to change
    // independently, and the day one of them re-rolls every map in the game is
    // a day the other should be untouched. See BattleMapGen::next() for why
    // mt_srand() is the wrong tool and why mul32 splits its operand.
    // =======================================================================

    private static function next(int &$state): int
    {
        $state = ($state + 0x9E3779B9) & 0xFFFFFFFF;
        $z = $state;
        $z = self::mul32($z ^ ($z >> 16), 0x85EBCA6B);
        $z = self::mul32($z ^ ($z >> 13), 0xC2B2AE35);
        return ($z ^ ($z >> 16)) & 0xFFFFFFFF;
    }

    /**
     * See BattleMapGen::mul32() for why the high partial product is masked to
     * sixteen bits BEFORE the shift. Getting that wrong is a float, silently,
     * and a different dungeon on a different build.
     */
    private static function mul32(int $a, int $b): int
    {
        $a &= 0xFFFFFFFF;
        $hi = ($a >> 16) & 0xFFFF;
        $lo = $a & 0xFFFF;
        return (((($hi * $b) & 0xFFFF) << 16) + ($lo * $b)) & 0xFFFFFFFF;
    }

    /**
     * Public because the printed book deals from a seeded stream too.
     *
     * AdventureBook rolls a wandering table for a specimen delve and it has to
     * come out the same every time the same seed is printed, which is this
     * generator's own discipline — so it uses this rather than growing a
     * second little LCG that would be one more thing to get subtly wrong.
     */
    public static function rint(int &$state, int $lo, int $hi): int
    {
        if ($hi <= $lo) {
            return $lo;
        }
        return $lo + (self::next($state) % ($hi - $lo + 1));
    }
}
